function makeReaderSummary(title) {
  const firstNote = topicNotes[title]?.[0];
  if (firstNote) {
    return firstNote;
  }
  return `${title}${topicParticle(title)} 처음 보는 독자도 상황을 빠르게 따라갈 수 있도록 장면과 반응을 나누어 정리한 글입니다.`;
}

