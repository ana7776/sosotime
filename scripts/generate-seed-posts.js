function hasFinalConsonant(text) {
  const chars = Array.from(text.normalize("NFC")).filter((char) => /[가-힣]/.test(char));
  if (!chars.length) return false;
  const code = chars[chars.length - 1].charCodeAt(0) - 0xac00;
  return code >= 0 && code % 28 !== 0;
}

function objectParticle(text) {
  return hasFinalConsonant(text) ? "을" : "를";
}

function topicParticle(text) {
  return hasFinalConsonant(text) ? "은" : "는";
}

function titleSlug(title) {
  return title
    .normalize("NFC")
    .toLowerCase()
    .replace(/[^0-9a-z가-힣\s-]/g, "")
    .trim()
    .replace(/\s+/g, "-")
    .replace(/-+/g, "-");
}

